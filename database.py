# Работа с базой данных SQLite

import os
import sqlite3
from datetime import date, timedelta

import bcrypt

# путь к файлу базы берётся из переменной окружения DB_PATH,
# если её нет - файл лежит рядом с этим файлом
DEFAULT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "gymlog.db")
DB_PATH = os.environ.get("DB_PATH", DEFAULT_PATH)


def get_connection():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row  # чтобы получать строки как словари
    conn.execute("PRAGMA foreign_keys = ON")  # в SQLite внешние ключи по умолчанию выключены
    return conn


def create_database():
    # создаём папку для базы, если её нет (например, /data на сервере)
    folder = os.path.dirname(DB_PATH)
    if folder:
        os.makedirs(folder, exist_ok=True)

    conn = get_connection()

    conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            email TEXT NOT NULL UNIQUE,
            password_hash TEXT NOT NULL
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS exercises (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            muscle TEXT NOT NULL,
            muscle_name TEXT NOT NULL,
            level INTEGER NOT NULL,
            description TEXT NOT NULL,
            main_muscles TEXT NOT NULL,
            extra_muscles TEXT,
            equipment TEXT NOT NULL,
            recommendation TEXT NOT NULL,
            steps TEXT NOT NULL,
            mistakes TEXT NOT NULL,
            image TEXT NOT NULL,
            image_alt TEXT NOT NULL
        )
    """)

    conn.execute("""
        CREATE TABLE IF NOT EXISTS records (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            exercise_id INTEGER NOT NULL,
            date TEXT NOT NULL,
            sets INTEGER NOT NULL,
            reps INTEGER NOT NULL,
            weight REAL,
            FOREIGN KEY (user_id) REFERENCES users (id),
            FOREIGN KEY (exercise_id) REFERENCES exercises (id)
        )
    """)

    # данные о себе: возраст, рост, вес (одна строка на пользователя)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS profiles (
            user_id INTEGER PRIMARY KEY,
            age INTEGER,
            height INTEGER,
            weight REAL,
            FOREIGN KEY (user_id) REFERENCES users (id)
        )
    """)

    # силовые показатели: какой вес и на сколько повторов человек может поднять
    conn.execute("""
        CREATE TABLE IF NOT EXISTS strength (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            user_id INTEGER NOT NULL,
            exercise_id INTEGER NOT NULL,
            date TEXT NOT NULL,
            weight REAL NOT NULL,
            reps INTEGER NOT NULL,
            FOREIGN KEY (user_id) REFERENCES users (id),
            FOREIGN KEY (exercise_id) REFERENCES exercises (id)
        )
    """)

    # добавляем упражнения, которых ещё нет в базе
    # (так новые упражнения появятся и в старой базе)
    for exercise in EXERCISES:
        found = conn.execute("SELECT id FROM exercises WHERE name = ?", (exercise[0],)).fetchone()
        if found is None:
            conn.execute("""
                INSERT INTO exercises (name, muscle, muscle_name, level, description,
                                       main_muscles, extra_muscles, equipment, recommendation,
                                       steps, mistakes, image, image_alt)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, exercise)

    conn.commit()
    conn.close()

    create_test_user()


# тестовый аккаунт для проверки, почта и пароль задаются переменными окружения
def create_test_user():
    email = os.environ.get("TEST_EMAIL")
    password = os.environ.get("TEST_PASSWORD")
    if not email or not password:
        return

    conn = get_connection()
    user = conn.execute("SELECT id FROM users WHERE email = ?", (email,)).fetchone()

    if user is None:
        password_hash = bcrypt.hashpw(password.encode("utf-8"), bcrypt.gensalt()).decode("utf-8")
        cursor = conn.execute(
            "INSERT INTO users (name, email, password_hash) VALUES (?, ?, ?)",
            ("Тестовый пользователь", email, password_hash),
        )
        user_id = cursor.lastrowid

        # несколько примерных записей, чтобы дневник не был пустым
        today = date.today()
        examples = [
            (user_id, 1, str(today - timedelta(days=1)), 4, 8, 60),
            (user_id, 2, str(today - timedelta(days=1)), 4, 8, 50),
            (user_id, 4, str(today - timedelta(days=3)), 3, 6, None),
        ]
        conn.executemany(
            "INSERT INTO records (user_id, exercise_id, date, sets, reps, weight) VALUES (?, ?, ?, ?, ?, ?)",
            examples,
        )

        # данные о себе и силовые за последний месяц, чтобы был виден прогресс
        conn.execute("INSERT INTO profiles (user_id, age, height, weight) VALUES (?, ?, ?, ?)",
                     (user_id, 20, 180, 75))
        strength = [
            (user_id, 2, str(today - timedelta(days=30)), 60, 5),
            (user_id, 2, str(today - timedelta(days=15)), 62.5, 5),
            (user_id, 2, str(today - timedelta(days=1)), 65, 5),
            (user_id, 1, str(today - timedelta(days=30)), 80, 5),
            (user_id, 1, str(today - timedelta(days=1)), 90, 5),
            (user_id, 4, str(today - timedelta(days=30)), 0, 6),
            (user_id, 4, str(today - timedelta(days=3)), 0, 8),
        ]
        conn.executemany(
            "INSERT INTO strength (user_id, exercise_id, date, weight, reps) VALUES (?, ?, ?, ?, ?)",
            strength,
        )
        conn.commit()

    conn.close()


